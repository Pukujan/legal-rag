import { octo, DB_SCHEMA } from "./config";
import type { QueryLogRow, StageTiming } from "../shared/types";

export class DbError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "DbError";
  }
}

async function runSql(sql: string): Promise<any[]> {
  if (!octo.configured()) {
    throw new DbError("The app database is not configured on this server.");
  }
  const res = await fetch(
    `${octo.baseUrl()}/api/workspaces/${octo.workspaceId()}/query`,
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${octo.apiKey()}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ sql }),
    },
  );
  if (!res.ok) {
    const detail = await res.text().catch(() => "");
    throw new DbError(`Database request failed (HTTP ${res.status}) ${detail.slice(0, 200)}`.trim());
  }
  const json = await res.json();
  return Array.isArray(json?.rows) ? json.rows : [];
}

/** PostgreSQL string literal. Null bytes and control characters are stripped first. */
function str(value: string | null | undefined): string {
  if (value === null || value === undefined) return "NULL";
  const safe = value.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, " ");
  return `'${safe.replace(/'/g, "''")}'`;
}

function num(value: number | null | undefined): string {
  return typeof value === "number" && Number.isFinite(value) ? String(value) : "NULL";
}

function bool(value: boolean | null | undefined): string {
  return value === true ? "TRUE" : value === false ? "FALSE" : "NULL";
}

function jsonb(value: unknown): string {
  return `${str(JSON.stringify(value ?? null))}::jsonb`;
}

function textArray(values: string[]): string {
  const clean = values.filter((v) => typeof v === "string" && v.length).slice(0, 50);
  if (!clean.length) return `'{}'::text[]`;
  return `ARRAY[${clean.map(str).join(", ")}]::text[]`;
}

const TABLE = `${DB_SCHEMA}.query_log`;

let ready: Promise<void> | null = null;

function ensureSchemaOnce(): Promise<void> {
  if (!ready) {
    ready = (async () => {
      await runSql(`CREATE SCHEMA IF NOT EXISTS ${DB_SCHEMA}`);
      await runSql(
        `CREATE TABLE IF NOT EXISTS ${TABLE} (
          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          question text NOT NULL,
          asked_at timestamptz NOT NULL,
          stages jsonb NOT NULL DEFAULT '[]'::jsonb,
          cited_case_ids text[] NOT NULL DEFAULT '{}',
          confidence double precision,
          abstain boolean NOT NULL DEFAULT FALSE,
          error text
        )`,
      );
      await runSql(
        `CREATE INDEX IF NOT EXISTS query_log_asked_at_idx ON ${TABLE} (asked_at DESC NULLS LAST)`,
      );
    })().catch((err) => {
      ready = null;
      throw err;
    });
  }
  return ready;
}

export interface InsertLogInput {
  question: string;
  stages: StageTiming[];
  citedCaseIds: string[];
  confidence: number | null;
  abstain: boolean;
  error: string | null;
}

/** Insert one anonymous row. `asked_at` is truncated to the hour on the way in. */
export async function insertQueryLog(input: InsertLogInput): Promise<number | null> {
  try {
    await ensureSchemaOnce();
    const rows = await runSql(
      `INSERT INTO ${TABLE} (question, asked_at, stages, cited_case_ids, confidence, abstain, error)
       VALUES (${str(input.question)}, date_trunc('hour', now()), ${jsonb(input.stages)},
               ${textArray(input.citedCaseIds)}, ${num(input.confidence)}, ${bool(input.abstain)}, ${str(input.error)})
       RETURNING id`,
    );
    const id = rows[0]?.id;
    return typeof id === "number" ? id : Number.isFinite(Number(id)) ? Number(id) : null;
  } catch (err) {
    console.error("[api] query log insert failed:", (err as Error).message);
    return null;
  }
}

function parseStageTimings(raw: unknown): StageTiming[] {
  let value: unknown = raw;
  if (typeof raw === "string") {
    try {
      value = JSON.parse(raw);
    } catch {
      return [];
    }
  }
  if (!Array.isArray(value)) return [];
  return value
    .map((s) => s as Partial<StageTiming>)
    .filter((s) => s && typeof s.stage === "string")
    .map((s) => ({
      stage: s.stage as string,
      duration_ms: typeof s.duration_ms === "number" ? s.duration_ms : null,
      elapsed_ms: typeof s.elapsed_ms === "number" ? s.elapsed_ms : null,
      skipped: s.skipped === true,
      reason: typeof s.reason === "string" ? s.reason : null,
      local: s.local === true,
      count: typeof s.count === "number" ? s.count : null,
    }));
}

export async function listQueryLog(limit = 200): Promise<QueryLogRow[]> {
  await ensureSchemaOnce();
  const capped = Math.max(1, Math.min(500, Math.floor(limit)));
  const rows = await runSql(
    `SELECT id, question, asked_at, stages, cited_case_ids, confidence, abstain, error
     FROM ${TABLE} ORDER BY asked_at DESC NULLS LAST, id DESC LIMIT ${capped}`,
  );
  return rows.map((r: any) => ({
    id: Number(r.id),
    question: String(r.question ?? ""),
    asked_at: String(r.asked_at ?? ""),
    stages: parseStageTimings(r.stages),
    cited_case_ids: Array.isArray(r.cited_case_ids) ? r.cited_case_ids.map(String) : [],
    confidence: r.confidence === null ? null : Number(r.confidence),
    abstain: Boolean(r.abstain),
    error: r.error === null ? null : String(r.error),
  }));
}

export async function logCount(): Promise<number | null> {
  try {
    await ensureSchemaOnce();
    const rows = await runSql(`SELECT COUNT(*)::int AS n FROM ${TABLE}`);
    return Number(rows[0]?.n ?? 0);
  } catch {
    return null;
  }
}

export function dbStatus(): { configured: boolean; reason: string | null } {
  if (!octo.configured()) {
    return { configured: false, reason: "The app database is not configured on this server." };
  }
  return { configured: true, reason: null };
}
